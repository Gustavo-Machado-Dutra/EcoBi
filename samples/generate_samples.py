def write_csv(path: Path, rows: List[Dict[str, Any]]) -> None:
    """Grava lista de dicionários em arquivo CSV UTF-8 com delimitação por vírgula."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)


def generate_all_samples(output_dir: Path | str = "samples") -> Dict[str, Path]:
    """Gera todos os arquivos de exemplo no diretório especificado."""
    target_dir = Path(output_dir)
    target_dir.mkdir(parents=True, exist_ok=True)

    piloto_path = target_dir / "ecobi_varejo_piloto.csv"
    adversos_path = target_dir / "ecobi_dados_adversos.csv"
    curto_path = target_dir / "ecobi_curto_insuficiente.csv"

    write_csv(piloto_path, generate_varejo_piloto())
    write_csv(adversos_path, generate_dados_adversos())
    write_csv(curto_path, generate_curto_insuficiente())

    return {
        "piloto": piloto_path,
        "adversos": adversos_path,
        "curto": curto_path,
    }


